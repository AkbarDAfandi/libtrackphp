function libtrack_categories(): array
{
    $categories = array_unique(array_column(libtrack_books(), 'category'));
    sort($categories);

    return $categories;
}

function libtrack_search_books(string $query): array
{
    $query = strtolower(trim($query));

    return array_values(array_filter(libtrack_books(), function (array $book) use ($query): bool {
        return str_contains(strtolower($book['title']), $query)
            || str_contains(strtolower($book['author']), $query)
            || str_contains(strtolower($book['category']), $query)
            || str_contains((string) $book['isbn'], $query);
    }));
}

